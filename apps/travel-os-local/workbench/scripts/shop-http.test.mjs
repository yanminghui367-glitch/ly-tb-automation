import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fork} from 'node:child_process';
test('real HTTP routing keeps simultaneous shop states/settings/SSE separate and rejects invalid shop scopes',async t=>{
 const dir=await mkdtemp(join(tmpdir(),'shop-http-'));
 await writeFile(join(dir,'shops.json'),JSON.stringify([{id:'wuzhou-changyou',name:'五洲畅游',port:9222},{id:'shop-7949a469',name:'环球领航',port:9230}]));
 const child=fork(new URL('./shop-http-fixture.mjs',import.meta.url),[],{env:{...process.env,WORKBENCH_NO_LISTEN:'1',WORKBENCH_TEST_RUNTIME:dir},stdio:['ignore','ignore','pipe','ipc']});
 let stderr='';child.stderr.on('data',b=>stderr+=b);
 t.after(async()=>{const exit=new Promise(r=>child.once('exit',r));child.kill();await exit;await rm(dir,{recursive:true,force:true});});
 const port=await new Promise((resolve,reject)=>{child.once('message',m=>resolve(m.port));child.once('exit',()=>reject(Error(stderr)));});
 const base='http://127.0.0.1:'+port;
 const req=async(path,input)=>{const r=await fetch(base+path,{method:input?'POST':'GET',headers:{Origin:'http://127.0.0.1:4318','content-type':'application/json'},body:input?JSON.stringify(input):undefined});return {status:r.status,data:await r.json()};};
 const [a,b]=await Promise.all([req('/api/v1/state'),req('/api/v1/state?executionShop=shop-7949a469')]);
 assert.equal(a.data.shop.id,'wuzhou-changyou');assert.equal(b.data.shop.id,'shop-7949a469');assert.equal(b.data.settings.executionEnabled,false);
 assert.equal((await req('/api/v1/settings?executionShop=shop-7949a469',{pool:'hqlh-only.xlsx'})).status,200);
 const nextA=await req('/api/v1/state'),nextB=await req('/api/v1/state?executionShop=shop-7949a469');
 assert.notEqual(nextA.data.settings.pool,'hqlh-only.xlsx');assert.equal(nextB.data.settings.pool,'hqlh-only.xlsx');
 assert.equal((await req('/api/v1/state?executionShop=missing')).status,409);
 assert.equal((await req('/api/batch/import?executionShop=shop-7949a469',{})).status,409);
 assert.equal((await req('/api/v1/start?executionShop=shop-7949a469',{id:'foreign-batch'})).status,409);
 assert.equal((await req('/api/os/state?executionShop=shop-7949a469')).data.engine.shop.id,'shop-7949a469');
 const controller=new AbortController();const stream=await fetch(base+'/api/v1/events?executionShop=shop-7949a469',{signal:controller.signal});
 const reader=stream.body.getReader();let text='';while(!text.includes('data:'))text+=new TextDecoder().decode((await reader.read()).value);controller.abort();
 assert.match(text,/shop-7949a469/);assert.doesNotMatch(text,/"shop":\{"id":"wuzhou-changyou"/);
 assert.equal((await fetch(base+'/shop-scope.js')).status,200);
});
